"""
export_geometry.py — Write the board geometry to shared/board_geometry.json.

The backend (Python) and frontend (JavaScript) each compute the board
geometry themselves. This file is the shared reference both test suites
compare against, so the two can't silently drift apart (e.g. intersection
ids getting numbered differently, which would make every API call refer to
the wrong spots).

Run from the backend folder after an intentional geometry change:
    uv run python -m scripts.export_geometry
"""

import json
from pathlib import Path

from board import DEFAULT_PORT_TYPES, PORT_SLOTS, build_hex_grid, build_intersection_map

FIXTURE_PATH = Path(__file__).resolve().parents[2] / "shared" / "board_geometry.json"


def build_geometry_fixture() -> dict:
    """Geometry in unit-hex coordinates (hex circumradius = 1, board centre = 0,0)."""
    hexes = build_hex_grid()
    intersections = build_intersection_map(hexes)
    return {
        "_comment": "Generated by backend/scripts/export_geometry.py. Do not edit by hand.",
        "hexes": [
            {"id": h.id, "x": round(h.cx, 6), "y": round(h.cy, 6)}
            for h in hexes
        ],
        "intersections": [
            {
                "id": i.id,
                "x": round(i.x, 6),
                "y": round(i.y, 6),
                "hex_ids": sorted(i.hex_ids),
                "adjacent_ids": sorted(i.adjacent_ids),
            }
            for i in intersections
        ],
        "port_slots": [list(slot) for slot in PORT_SLOTS],
        "default_port_types": list(DEFAULT_PORT_TYPES),
    }


def main() -> None:
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(json.dumps(build_geometry_fixture(), indent=2) + "\n")
    print(f"Wrote {FIXTURE_PATH}")


if __name__ == "__main__":
    main()
